//! `oauth/*`: the OAuth action route for the five kept providers.
//!
//! The providers that left with their tooling (cursor, kiro, kimi, qoder, xai,
//! github, gemini-cli, antigravity, codebuddy-cn, kimchi, trae, windsurf, zed,
//! xiaomi-mimo) are absent here, so the `start-proxy` / `poll-status` /
//! `manual-code` / `ide-status` actions that existed only for them are gone.
//! What stays is what the kept providers use: `authorize`, `device-code`,
//! `exchange` and `poll`, plus the codex proxy session actions.

use std::collections::HashMap;

use axum::Json;
use axum::extract::{Path, Query, State};
use axum::response::{IntoResponse, Response};
use serde_json::{Map, Value, json};

use crate::error::ApiError;
use crate::services::codex_proxy;
use crate::state::AppState;

/// A `Json` body, or `{}` when the request sent none.
fn body_object(payload: Option<&Value>) -> Map<String, Value> {
    payload
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default()
}

/// `GET /api/oauth/{provider}/{action}`.
pub async fn get(
    State(state): State<AppState>,
    Path((provider, action)): Path<(String, String)>,
    Query(query): Query<HashMap<String, String>>,
) -> Response {
    match action.as_str() {
        "authorize" => {
            let redirect_uri = query
                .get("redirect_uri")
                .cloned()
                .unwrap_or_else(|| "http://localhost:8080/callback".to_string());
            let mut meta = Map::new();
            for (k, v) in &query {
                if k != "redirect_uri" {
                    meta.insert(k.clone(), Value::String(v.clone()));
                }
            }
            match router_sse::services::oauth_flow::generate_auth_data(
                &provider,
                &redirect_uri,
                &meta,
            ) {
                Ok(data) => Json(data.to_json()).into_response(),
                Err(e) => ApiError::internal(e).into_response(),
            }
        }
        "device-code" => {
            match router_sse::services::oauth_flow::request_device_code(&provider, None).await {
                Ok(mut data) => {
                    // `codeVerifier` is always returned; for the kept providers
                    // it is the generic PKCE verifier, generated by the
                    // authorize step the client calls first.
                    if let Value::Object(map) = &mut data {
                        map.insert("codeVerifier".into(), Value::Null);
                    }
                    Json(data).into_response()
                }
                Err(e) => ApiError::bad_request(e).into_response(),
            }
        }
        "start-proxy" => {
            if provider != "codex" {
                return ApiError::bad_request("Proxy only supported for codex").into_response();
            }
            let Some(app_port) = query.get("app_port").and_then(|p| p.parse::<u16>().ok()) else {
                return ApiError::bad_request("Missing app_port").into_response();
            };
            let result = codex_proxy::start_proxy(state, app_port).await;
            let mut server_side = false;
            if result.get("success").and_then(Value::as_bool) == Some(true)
                && let (Some(s), Some(cv), Some(ru)) = (
                    query.get("state"),
                    query.get("code_verifier"),
                    query.get("redirect_uri"),
                )
            {
                server_side = codex_proxy::register_session(s, cv, ru);
            }
            let mut out = result;
            if let Value::Object(map) = &mut out {
                map.insert("serverSide".into(), Value::Bool(server_side));
            }
            Json(out).into_response()
        }
        "poll-status" => {
            let Some(state_key) = query.get("state") else {
                return ApiError::bad_request("Missing state").into_response();
            };
            if provider != "codex" {
                return ApiError::bad_request("Poll only supported for codex").into_response();
            }
            let Some(session) = codex_proxy::session_status(state_key) else {
                return Json(json!({ "status": "unknown" })).into_response();
            };
            let mut payload = json!({
                "status": session.status,
                "codeVerifier": session.code_verifier,
                "redirectUri": session.redirect_uri,
            });
            if let Some(err) = &session.error
                && let Value::Object(map) = &mut payload
            {
                map.insert("error".into(), Value::String(err.clone()));
            }
            if let Some(id) = &session.connection_id
                && let Value::Object(map) = &mut payload
            {
                map.insert("connectionId".into(), Value::String(id.clone()));
            }
            if let Some(email) = &session.email
                && let Value::Object(map) = &mut payload
            {
                map.insert("email".into(), Value::String(email.clone()));
            }
            if session.status == "done" || session.status == "error" {
                codex_proxy::clear_session(state_key);
            }
            Json(payload).into_response()
        }
        "stop-proxy" => {
            if provider != "codex" {
                return ApiError::bad_request("Proxy only supported for codex").into_response();
            }
            codex_proxy::stop_proxy();
            Json(json!({ "success": true })).into_response()
        }
        _ => ApiError::bad_request("Unknown action").into_response(),
    }
}

/// `POST /api/oauth/{provider}/{action}`.
pub async fn post(
    State(state): State<AppState>,
    Path((provider, action)): Path<(String, String)>,
    Query(query): Query<HashMap<String, String>>,
    body: Result<Json<Value>, axum::extract::rejection::JsonRejection>,
) -> Response {
    let Ok(Json(payload)) = body else {
        return ApiError::bad_request("Invalid or empty request body").into_response();
    };
    let body = body_object(Some(&payload));

    match action.as_str() {
        "register-session" => {
            let state_key = query.get("state").cloned().or_else(|| {
                body.get("state")
                    .and_then(Value::as_str)
                    .map(str::to_string)
            });
            let Some(state_key) = state_key else {
                return ApiError::bad_request("Missing state").into_response();
            };
            if provider != "codex" {
                return ApiError::bad_request("register-session only supported for codex")
                    .into_response();
            }
            let ok = codex_proxy::register_session(
                &state_key,
                body.get("codeVerifier")
                    .and_then(Value::as_str)
                    .unwrap_or(""),
                body.get("redirectUri")
                    .and_then(Value::as_str)
                    .unwrap_or(""),
            );
            Json(json!({ "success": ok })).into_response()
        }
        "exchange" => exchange(state, &provider, &body).await,
        "poll" => poll(state, &provider, &body).await,
        _ => ApiError::bad_request("Unknown action").into_response(),
    }
}

/// The `exchange` action, minus the branches whose providers were dropped.
async fn exchange(state: AppState, provider: &str, body: &Map<String, Value>) -> Response {
    let code = body.get("code").and_then(Value::as_str).unwrap_or("");
    let redirect_uri = body
        .get("redirectUri")
        .and_then(Value::as_str)
        .unwrap_or("");
    let code_verifier = body
        .get("codeVerifier")
        .and_then(Value::as_str)
        .unwrap_or("");
    let state_key = body.get("state").and_then(Value::as_str).unwrap_or("");
    let meta = body
        .get("meta")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();

    // A raw JWT pasted in place of a code is an access token, not a grant.
    if code.starts_with("eyJ") && code.contains('.') {
        return import_access_token(state, provider, code).await;
    }

    if code.is_empty() || redirect_uri.is_empty() || code_verifier.is_empty() {
        return ApiError::bad_request("Missing required fields").into_response();
    }

    let tokens = match router_sse::services::oauth_flow::exchange_tokens(
        provider,
        code,
        redirect_uri,
        code_verifier,
        state_key,
        &meta,
    )
    .await
    {
        Ok(t) => t,
        Err(e) => return ApiError::internal(e).into_response(),
    };

    save_and_report(state, provider, "oauth", tokens).await
}

/// The `poll` action for device-code providers.
async fn poll(state: AppState, provider: &str, body: &Map<String, Value>) -> Response {
    let Some(device_code) = body.get("deviceCode").and_then(Value::as_str) else {
        return ApiError::bad_request("Missing device code").into_response();
    };
    let code_verifier = body.get("codeVerifier").and_then(Value::as_str);
    let extra = body.get("extraData");

    // kilocode and codebuddy-intl complete without PKCE; grok-cli likewise.
    let result = match router_sse::services::oauth_flow::poll_for_token(
        provider,
        device_code,
        code_verifier,
        extra,
    )
    .await
    {
        Ok(r) => r,
        Err(e) => return ApiError::bad_request(e).into_response(),
    };

    if result.success {
        let tokens = result.tokens.unwrap_or(Value::Null);
        return save_and_report(state, provider, "oauth", tokens).await;
    }

    Json(json!({
        "success": false,
        "error": result.error,
        "errorDescription": result.error_description,
        "pending": result.pending
            || result.error.as_deref() == Some("authorization_pending")
            || result.error.as_deref() == Some("slow_down"),
    }))
    .into_response()
}

/// The `eyJ…` branch: store the pasted JWT as an access-token connection.
async fn import_access_token(state: AppState, provider: &str, token: &str) -> Response {
    let info = router_sse::services::oauth_flow::extract_codex_account_info(token);
    let direct =
        router_sse::services::oauth_flow::decode_jwt_payload(token).unwrap_or_else(|| json!({}));
    let account_id = info
        .get("chatgptAccountId")
        .filter(|v| !v.is_null())
        .or_else(|| direct.get("account_id"));
    let plan_type = info
        .get("chatgptPlanType")
        .filter(|v| !v.is_null())
        .or_else(|| direct.get("plan_type"));
    let email = info
        .get("email")
        .filter(|v| !v.is_null())
        .or_else(|| direct.get("email"));

    let mut psd = Map::new();
    psd.insert("authMethod".into(), Value::String("access_token".into()));
    if let Some(id) = account_id {
        psd.insert("chatgptAccountId".into(), id.clone());
    }
    if let Some(plan) = plan_type {
        psd.insert("chatgptPlanType".into(), plan.clone());
    }

    let data = json!({
        "provider": provider,
        "authType": "access_token",
        "accessToken": token,
        "email": email.cloned().unwrap_or(Value::Null),
        "providerSpecificData": Value::Object(psd),
        "testStatus": "active",
    });

    match state
        .write(move |tx| router_db::repos::connections::create_provider_connection(tx, &data))
        .await
    {
        Ok(c) => Json(json!({
            "success": true,
            "connection": {
                "id": c.get("id").cloned().unwrap_or(Value::Null),
                "provider": c.get("provider").cloned().unwrap_or(Value::Null),
                "email": c.get("email").cloned().unwrap_or(Value::Null),
                "displayName": c.get("displayName").cloned().unwrap_or(Value::Null),
            }
        }))
        .into_response(),
        Err(e) => ApiError::internal(e.to_string()).into_response(),
    }
}

/// `createProviderConnection({provider, authType, ...tokens, expiresAt,
/// testStatus})` then the `{success, connection:{id, provider, email,
/// displayName}}` shape.
async fn save_and_report(
    state: AppState,
    provider: &str,
    auth_type: &str,
    tokens: Value,
) -> Response {
    let data = codex_proxy::connection_payload(provider, auth_type, tokens);
    match state
        .write(move |tx| router_db::repos::connections::create_provider_connection(tx, &data))
        .await
    {
        Ok(c) => Json(json!({
            "success": true,
            "connection": {
                "id": c.get("id").cloned().unwrap_or(Value::Null),
                "provider": c.get("provider").cloned().unwrap_or(Value::Null),
                "email": c.get("email").cloned().unwrap_or(Value::Null),
                "displayName": c.get("displayName").cloned().unwrap_or(Value::Null),
            }
        }))
        .into_response(),
        Err(e) => ApiError::internal(e.to_string()).into_response(),
    }
}

